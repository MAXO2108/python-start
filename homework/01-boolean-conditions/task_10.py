# ДЗ 1, задача 10 «Допуск к экзамену» (★★☆)
# Задачник, задача 2.2.11: https://python-theory-makarov.vercel.app/zadachnik/2-2/index.html#p11
#
# Студента допускают к экзамену, если посещаемость не ниже 75%, сдано не меньше 8 лабораторных
# работ и нет долга по оплате. Вводятся посещаемость в процентах, число сданных работ и сумма
# долга. Выведите результат каждой проверки и общий ответ.
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     80
#     8
#     0
#   в терминале:
#     Посещаемость, %: 80
#     Сдано лабораторных: 8
#     Долг по оплате, руб.: 0
#     Посещаемость: True
#     Лабораторные: True
#     Нет долга: True
#     Допущен: True
# Пример 2
#   ввод:
#     90
#     6
#     0
#   в терминале:
#     Посещаемость, %: 90
#     Сдано лабораторных: 6
#     Долг по оплате, руб.: 0
#     Посещаемость: True
#     Лабораторные: False
#     Нет долга: True
#     Допущен: False
# Пример 3
#   ввод:
#     75
#     10
#     1500
#   в терминале:
#     Посещаемость, %: 75
#     Сдано лабораторных: 10
#     Долг по оплате, руб.: 1500
#     Посещаемость: True
#     Лабораторные: True
#     Нет долга: False
#     Допущен: False

# Решение
pos = int(input("Посещаемость, %: "))
works = int(input("Сдано лабораторных: "))
debt = int(input("Долг по оплате, руб.: "))
answer1 = pos >= 75
answer2 = works >= 8
answer3 = debt == 0
answer4 = answer1 and answer2 and answer3
print(f"Посещаемость: {answer1}")
print(f"Сдано лабораторных: {answer2}")
print(f"Долг по работе: {answer3}")
print(f"Допущен: {answer4}")